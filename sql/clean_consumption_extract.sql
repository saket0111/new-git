-- Read-only. Reproduces the cleaned monthly consumption table. No values altered.
-- Net consumption = 261 (issue) minus 262 (reversal). Target for forecasting is QUANTITY, never price.
-- IS_BACKCAST_PERIOD='Y' (all of 2023) is carried through so the commander can include or exclude it.
CREATE VIEW-LIKE QUERY (run as SELECT):

WITH M AS (
  SELECT MATERIAL_ID, PLANT_ID, POSTING_DATE, MOVEMENT_TYPE, QUANTITY, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_001
  UNION ALL SELECT MATERIAL_ID, PLANT_ID, POSTING_DATE, MOVEMENT_TYPE, QUANTITY, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_002
  UNION ALL SELECT MATERIAL_ID, PLANT_ID, POSTING_DATE, MOVEMENT_TYPE, QUANTITY, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_003
  UNION ALL SELECT MATERIAL_ID, PLANT_ID, POSTING_DATE, MOVEMENT_TYPE, QUANTITY, IS_BACKCAST_PERIOD FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_004
)
SELECT TO_VARCHAR(M.POSTING_DATE,'YYYY-MM')      AS YEAR_MONTH,
       M.MATERIAL_ID, M.PLANT_ID, D.MATERIAL_TYPE, D.MATERIAL_GROUP,
       C.BUSINESS_CATEGORY, G.BASE_UOM, D.CRITICALITY, D.NM_SM_CLASS,
       D.PLANNED_DELIVERY_DAYS,
       MAX(CASE WHEN M.IS_BACKCAST_PERIOD='Y' THEN 'Y' ELSE 'N' END) AS IS_BACKCAST_PERIOD,
       SUM(CASE WHEN M.MOVEMENT_TYPE='261' THEN M.QUANTITY
                WHEN M.MOVEMENT_TYPE='262' THEN -M.QUANTITY END)     AS NET_CONSUMPTION_QTY
FROM M
JOIN VEDANTA_POC.DIM_MATERIAL D          ON D.MATERIAL_ID = M.MATERIAL_ID
LEFT JOIN VEDANTA_POC.CATEGORY_MAP C     ON C.MATERIAL_GROUP = D.MATERIAL_GROUP
LEFT JOIN VEDANTA_POC.REF_MATERIAL_GROUP G ON G.MATERIAL_GROUP = D.MATERIAL_GROUP
WHERE M.MOVEMENT_TYPE IN ('261','262')
  AND D.MATERIAL_TYPE IN ('ZSPR','ZSPN')
GROUP BY TO_VARCHAR(M.POSTING_DATE,'YYYY-MM'), M.MATERIAL_ID, M.PLANT_ID, D.MATERIAL_TYPE,
         D.MATERIAL_GROUP, C.BUSINESS_CATEGORY, G.BASE_UOM, D.CRITICALITY, D.NM_SM_CLASS, D.PLANNED_DELIVERY_DAYS;

